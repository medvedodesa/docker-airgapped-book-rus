#!/usr/bin/env bash
# Чеклист отнесения объекта КИИ к категории по Приказу ФСТЭК №235
# Диагностика, не является официальным юридическим заключением
# Использование: bash kii-category-checklist.sh
set -euo pipefail

PASS=0; WARN=0; FAIL=0

ok()   { echo "  [ДА]   $1"; ((PASS++)); }
warn() { echo "  [???]  $1"; ((WARN++)); }
fail() { echo "  [НЕТ]  $1"; ((FAIL++)); }

echo "=== Чеклист категорирования объекта КИИ ==="
echo "  Приказ ФСТЭК России №235 от 21.12.2017"
echo "  Методические рекомендации ФСТЭК по категорированию"
echo ""
echo "  ВНИМАНИЕ: Скрипт выполняет техническую диагностику."
echo "  Окончательное категорирование выполняет комиссия организации."
echo ""

# Принадлежность к сфере КИИ
echo "--- Отраслевая принадлежность ---"
echo "  Организация осуществляет деятельность в сферах:"
echo "  (отметьте вручную применимые пункты)"
echo ""
for sector in \
  "Здравоохранение" \
  "Наука" \
  "Транспорт" \
  "Связь" \
  "Энергетика" \
  "Банковская сфера и финансовые рынки" \
  "Топливно-энергетический комплекс" \
  "Атомная промышленность" \
  "Оборонная промышленность" \
  "Ракетно-космическая промышленность" \
  "Горнодобывающая промышленность" \
  "Металлургическая промышленность" \
  "Химическая промышленность"; do
  echo "    [ ] $sector"
done

# Технические признаки КИИ
echo ""
echo "--- Технические признаки (автоматическая проверка) ---"

# Управление технологическими процессами
if docker ps 2>/dev/null | grep -qiE "scada|plc|ics|industrial|opc"; then
  ok "Обнаружены контейнеры АСУ ТП/SCADA"
else
  warn "АСУ ТП/SCADA в Docker не обнаружены (проверьте наличие внешних систем)"
fi

# Изолированная сеть
if ip route 2>/dev/null | grep -v "default" | grep -qE "10\.|172\.|192\.168\."; then
  ok "Изолированные внутренние сети обнаружены"
else
  warn "Изолированная сетевая инфраструктура не обнаружена"
fi

# Требования к непрерывности
echo ""
echo "--- Критичность нарушения функционирования ---"
echo "  Оцените последствия нарушения работы системы:"
echo ""
echo "  Категория 1 (ЗНАЧИМАЯ НАИВЫСШАЯ) — если нарушение может повлечь:"
echo "    [ ] Угрозу жизни и здоровью более 500 человек"
echo "    [ ] Прекращение или нарушение критической инфраструктуры"
echo "    [ ] Ущерб федеральному бюджету более 1 млрд руб."
echo ""
echo "  Категория 2 — если нарушение может повлечь:"
echo "    [ ] Угрозу жизни 50-500 человек"
echo "    [ ] Ущерб бюджету 50 млн - 1 млрд руб."
echo ""
echo "  Категория 3 — если нарушение может повлечь:"
echo "    [ ] Угрозу жизни до 50 человек"
echo "    [ ] Ущерб бюджету до 50 млн руб."

# Мероприятия при KII
echo ""
echo "--- Обязательные меры по 187-ФЗ ---"
echo ""

# Проверка наличия регламентов
for doc in \
  "/etc/kii/security-policy.md" \
  "/etc/kii/incident-response.md" \
  "/opt/kii/category-decision.pdf" \
  "/opt/kii/security-plan.pdf"; do
  [ -f "$doc" ] && ok "Документ: $doc" || warn "Документ не найден: $doc"
done

# Регистрация в ФСТЭК
echo ""
echo "--- Регистрация ---"
echo "  Объект КИИ должен быть зарегистрирован в реестре ФСТЭК"
echo "  Срок подачи сведений — 10 дней после категорирования (ПП-127)"
echo ""
echo "  [ ] Проведено категорирование комиссией"
echo "  [ ] Акт категорирования подписан"
echo "  [ ] Сведения направлены в ФСТЭК"
echo "  [ ] Получено подтверждение регистрации"

echo ""
echo "=== Результаты автоматической проверки ==="
echo "  PASS=$PASS  WARN=$WARN  FAIL=$FAIL"
echo ""
echo "  Для официального категорирования обратитесь:"
echo "  - ФСТЭК России: fstec.ru"
echo "  - Методические рекомендации: рекомендации по категорированию"
